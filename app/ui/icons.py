_cache: dict = {}


def _pixmap(paths: str, color: str, size: int) -> QPixmap:
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
           f'stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round">{paths}</svg>')
    renderer = QSvgRenderer(QByteArray(svg.encode()))
    ratio = 2  # net sur écrans haute densité
    image = QImage(size * ratio, size * ratio, QImage.Format.Format_ARGB32_Premultiplied)
    image.fill(Qt.GlobalColor.transparent)
    painter = QPainter(image)
    renderer.render(painter)
    painter.end()
    pix = QPixmap.fromImage(image)
    pix.setDevicePixelRatio(ratio)
    return pix


def nav_icon(emoji: str, normal: str = "#cbd5e1", active: str = "#ffffff", size: int = 20) -> Optional[QIcon]:
    """Icône en traits pour l'emoji du menu ; None si aucune icône n'est prévue (l'emoji reste alors affiché)."""
    paths = _PATHS.get(emoji)
    if paths is None:
        return None
    key = (emoji, normal, active, size)
    if key not in _cache:
        icon = QIcon()
        icon.addPixmap(_pixmap(paths, normal, size), QIcon.Mode.Normal, QIcon.State.Off)
        icon.addPixmap(_pixmap(paths, active, size), QIcon.Mode.Normal, QIcon.State.On)
        _cache[key] = icon
    return _cache[key]


def line_icon(key: str, color: str = "#c62f3a", size: int = 18) -> Optional[QIcon]:
    """Petite icône en traits (corbeille…) d'une couleur donnée."""
    paths = _PATHS.get(key)
    if paths is None:
        return None
    cache_key = ("line", key, color, size)
    if cache_key not in _cache:
        icon = QIcon(_pixmap(paths, color, size))
        _cache[cache_key] = icon
    return _cache[cache_key]
